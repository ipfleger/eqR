#' Expand frequency table to raw data
#' Use this to mimic "item level" data when we only have total score counts
counts_to_data <- function(scores, counts) {
  # Repeat each score 'count' times
  raw_vec <- rep(scores, times = counts)
  # Return as a dataframe with a single column (treating Total Score as 1 item)
  score_dat <- matrix(0, nrow = sum(counts), ncol = max(scores)) |>
    `colnames<-`(paste0("item_", 1:max(scores))) |>
    as.data.frame() |>
    tibble::rowid_to_column(var = "id")
  for(x in 1:max(scores)){
    score_dat[raw_vec >= x, paste0("item_", x)] <- 1
  }
  score_dat
}

